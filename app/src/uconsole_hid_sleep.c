/*
 * uConsole host sleep control via HID Kana indicator.
 *
 * HID Kana ON:
 *   - Disable trackpad
 *   - Suspend keyboard backlight
 *   - Activate LOCK layer
 *
 * HID Kana OFF:
 *   - Deactivate LOCK layer
 *   - Resume keyboard backlight
 *   - Enable trackpad
 *
 * The Kana HID indicator is intentionally repurposed as
 * a private host -> keyboard sleep control bit.
 *
 * SPDX-License-Identifier: MIT
 */

#include <stdbool.h>
#include <stdint.h>

#include <zephyr/logging/log.h>

#include <zmk/event_manager.h>
#include <zmk/events/hid_indicators_changed.h>

#include <zmk/backlight.h>
#include <zmk/keymap.h>
#include <zmk/trackpad.h>

LOG_MODULE_DECLARE(zmk, CONFIG_ZMK_LOG_LEVEL);

/*
 * Standard keyboard HID LED Output Report:
 *
 * bit 0 = Num Lock
 * bit 1 = Caps Lock
 * bit 2 = Scroll Lock
 * bit 3 = Compose
 * bit 4 = Kana
 *
 * Kana is reserved by this firmware for host controlled
 * keyboard sleep/lock.
 */
#define UCONSOLE_HID_INDICATOR_KANA (1U << 4)

/*
 * IMPORTANT:
 *
 * This must match LOCK in the bb9900.keymap actually being built:
 *
 *   #define LOCK 5
 *
 * The current local keymap layout is:
 *
 *   0 = default
 *   1 = SYM
 *   2 = UPPER
 *   3 = GAME
 *   4 = MOUSE
 *   5 = LOCK
 *   6 = UNLOCK
 *   7 = BOOT
 */
#define UCONSOLE_LOCK_LAYER 5

/*
 * Enter keyboard sleep.
 *
 * Explicit state-setting APIs are used instead of &tog LOCK,
 * making host sleep requests idempotent.
 */
static void uconsole_sleep(void)
{
    int ret;

    LOG_INF("uConsole: entering keyboard sleep");

    /*
     * Stop trackpad processing first.
     */
    zmk_trackpad_set_enabled(false);

    /*
     * Suspend instead of turning the backlight off.
     *
     * This preserves the previous backlight state so RESUME
     * can restore it later.
     */
    ret = zmk_backlight_suspend();

    if (ret < 0) {
        LOG_ERR("uConsole: backlight suspend failed: %d", ret);
    }

    /*
     * Explicitly activate LOCK.
     *
     * Do not use &tog LOCK here because sleep is a state,
     * not a toggle operation.
     */
    ret = zmk_keymap_layer_activate(UCONSOLE_LOCK_LAYER);

    if (ret < 0) {
        LOG_ERR("uConsole: LOCK layer activation failed: %d", ret);
    }
}

/*
 * Leave keyboard sleep.
 */
static void uconsole_wake(void)
{
    int ret;

    LOG_INF("uConsole: leaving keyboard sleep");

    /*
     * Remove LOCK first so normal key processing is restored.
     */
    ret = zmk_keymap_layer_deactivate(UCONSOLE_LOCK_LAYER);

    if (ret < 0) {
        LOG_ERR("uConsole: LOCK layer deactivation failed: %d", ret);
    }

    /*
     * Restore the backlight state which existed before
     * zmk_backlight_suspend().
     */
    ret = zmk_backlight_resume();

    if (ret < 0) {
        LOG_ERR("uConsole: backlight resume failed: %d", ret);
    }

    /*
     * Finally restore trackpad processing.
     */
    zmk_trackpad_set_enabled(true);
}

/*
 * Receive HID indicator changes generated by hid_indicators.c.
 */
static int uconsole_hid_sleep_listener(const zmk_event_t *eh)
{
    const struct zmk_hid_indicators_changed *ev =
        as_zmk_hid_indicators_changed(eh);

    if (ev == NULL) {
        return ZMK_EV_EVENT_BUBBLE;
    }

    /*
     * Kana is bit 4 of the keyboard LED Output Report.
     */
    const bool kana =
        (ev->indicators & UCONSOLE_HID_INDICATOR_KANA) != 0;

    /*
     * Layer 5 is the source of truth.
     *
     * Do not maintain a separate "uconsole_sleeping" bool,
     * because LOCK can also be changed independently by Fn+Esc.
     */
    const bool locked =
        zmk_keymap_layer_active(UCONSOLE_LOCK_LAYER);

    /*
     * Host requested state is already satisfied.
     *
     * This also prevents repeated HID indicator events from
     * repeatedly suspending/resuming the backlight.
     */
    if (kana == locked) {
        return ZMK_EV_EVENT_BUBBLE;
    }

    if (kana) {
        uconsole_sleep();
    } else {
        uconsole_wake();
    }

    return ZMK_EV_EVENT_BUBBLE;
}

/*
 * hid_indicators.c already raises zmk_hid_indicators_changed
 * whenever the host LED report/current endpoint changes.
 */
ZMK_LISTENER(
    uconsole_hid_sleep,
    uconsole_hid_sleep_listener
);

ZMK_SUBSCRIPTION(
    uconsole_hid_sleep,
    zmk_hid_indicators_changed
);
