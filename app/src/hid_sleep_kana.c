/*
 * Host sleep control via HID Kana indicator.
 *
 * HID Kana ON:
 *   - Disable trackpad
 *   - Suspend keyboard backlight
 *   - Activate LOCK layer
 *
 * HID Kana OFF:
 *   - Deactivate LOCK layer
 *   - Resume keyboard backlight
 *   - Enable trackpad
 *
 * The Kana HID indicator is intentionally repurposed as
 * a private host -> keyboard sleep control bit.
 *
 * SPDX-License-Identifier: MIT
 */

#include <stdbool.h>
#include <stdint.h>

#include <zephyr/logging/log.h>

#include <zmk/activity.h>
#include <zmk/event_manager.h>
#include <zmk/events/hid_indicators_changed.h>

#include <zmk/backlight.h>
#include <zmk/host_lock.h>
#include <zmk/keymap.h>
#include <zmk/led_fade.h>
#include <zmk/trackpad.h>

LOG_MODULE_DECLARE(zmk, CONFIG_ZMK_LOG_LEVEL);

/*
 * Standard keyboard HID LED Output Report:
 *
 * bit 0 = Num Lock
 * bit 1 = Caps Lock
 * bit 2 = Scroll Lock
 * bit 3 = Compose
 * bit 4 = Kana
 *
 * Kana is reserved by this firmware for host controlled
 * keyboard sleep/lock.
 */
#define HOST_HID_INDICATOR_KANA (1U << 4)

/*
 * IMPORTANT:
 *
 * This must match LOCK in the bb9900.keymap actually being built:
 *
 *   #define LOCK 5
 *
 * The current local keymap layout is:
 *
 *   0 = default
 *   1 = SYM
 *   2 = UPPER
 *   3 = GAME
 *   4 = MOUSE
 *   5 = LOCK
 *   6 = UNLOCK_LEFT
 *   7 = UNLOCK_RIGHT
 *   8 = CONFIG
 */
static bool host_locked;
static bool host_kana_last;
static bool backlight_should_restore_after_lock;

bool zmk_host_lock_active(void)
{
    return host_locked;
}

/*
 * Enter keyboard sleep.
 *
 * Explicit state-setting APIs are used instead of &tog LOCK,
 * making host sleep requests idempotent.
 */
static void host_lock_sleep(void)
{
    int ret;

    LOG_INF("Host lock: entering keyboard sleep");

    backlight_should_restore_after_lock =
        zmk_backlight_is_on() || zmk_backlight_was_idle_auto_off();

    /*
     * Do not use &tog LOCK here because sleep is a state,
     * not a toggle operation.
     */
    ret = zmk_host_lock_engage(ZMK_LED_FADE_DURATION_MS);
    if (ret < 0) {
        LOG_ERR("Host lock: LOCK layer activation failed: %d", ret);
    }
}

/*
 * Leave keyboard sleep.
 */
static void host_lock_wake(void)
{
    int ret;

    LOG_INF("Host lock: leaving keyboard sleep");

    /* Clear both the host lock and any manual lock layered over it. */
    ret = zmk_host_lock_force_unlock();

    if (ret < 0) {
        LOG_ERR("Host lock: force unlock failed: %d", ret);
    }

    zmk_host_lock_release(backlight_should_restore_after_lock);
    backlight_should_restore_after_lock = false;
}

/*
 * Receive HID indicator changes generated by hid_indicators.c.
 */
static int host_lock_hid_sleep_listener(const zmk_event_t *eh)
{
    const struct zmk_hid_indicators_changed *ev =
        as_zmk_hid_indicators_changed(eh);

    if (ev == NULL) {
        return ZMK_EV_EVENT_BUBBLE;
    }

    /*
     * Kana is bit 4 of the keyboard LED Output Report.
     */
    const bool kana =
        (ev->indicators & HOST_HID_INDICATOR_KANA) != 0;

    /*
     * Only a Kana change counts, so other LED changes never lock or unlock.
     * Kana OFF clears a manual lock too, but only as a change from ON.
     */
    const bool kana_changed = kana != host_kana_last;
    host_kana_last = kana;

    if (!kana_changed) {
        return ZMK_EV_EVENT_BUBBLE;
    }

    if (kana) {
        if (!host_locked) {
            host_locked = true;
            host_lock_sleep();
        }
    } else if (host_locked || zmk_keymap_layer_active(ZMK_HOST_LOCK_LAYER)) {
        host_locked = false;
        host_lock_wake();
    }

    return ZMK_EV_EVENT_BUBBLE;
}

/*
 * hid_indicators.c already raises zmk_hid_indicators_changed
 * whenever the host LED report/current endpoint changes.
 */
ZMK_LISTENER(
    host_lock_hid_sleep,
    host_lock_hid_sleep_listener
);

ZMK_SUBSCRIPTION(
    host_lock_hid_sleep,
    zmk_hid_indicators_changed
);
